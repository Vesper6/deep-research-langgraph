def hit(question: str, keyword: str, k: int) -> bool:
    """搜出来的前 k 块里，有没有包含关键词的那一块"""
    for h in search_kb(question, k=k):
        if keyword in h["text"]:
            return True
    return False


if __name__ == "__main__":
    for k in [1, 3]:
        ok = 0
        for question, keyword in CASES:
            if hit(question, keyword, k):
                ok += 1
            else:
                print(f"  ❌ k={k} 没找到：{question}")
        print(f"k={k}：命中 {ok}/{len(CASES)} = {ok / len(CASES):.0%}\n")
